export function dialogueFor(levelId: number, hero: HeroId) {
  const base = DIALOGUES[levelId];
  if (!base) return null;
  const lines = base.lines.filter((line) => line.speaker !== hero);
  const reply = REPLIES[levelId]?.[hero];
  return {
    title: base.title,
    lines: reply ? [...lines, reply] : lines,
  };
}

const lastByPool = new Map<string, number>();

export const randomLine = (arr: string[], pool?: string) => {
  if (arr.length === 0) return "";
  if (arr.length === 1) return arr[0];
  const key = pool ?? arr[0] ?? "line";
  const last = lastByPool.get(key);
  let i = Math.floor(Math.random() * arr.length);
  let tries = 0;
  while (i === last && tries++ < 12) i = Math.floor(Math.random() * arr.length);
  lastByPool.set(key, i);
  return arr[i];
};
